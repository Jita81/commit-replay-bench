// exmap/src/export/feature.ts — requirement.feature: Gherkin from the live map (design §12.4). Feature = the story,
// one Rule per live rule in card_order, one Scenario per live example under its rule (Given/When/Then when the text
// parses, else a single "* <text>" step), questions and definitions as comments. No Background, no tables, no invented
// steps (a story or rule line Gherkin would read as structure is written as a comment), no tabs; ends with exactly one "\n".
import type { Definition, ExampleCard, QuestionCard } from "../core/types.js";
import type { ExportContext } from "./index.js";
import { acceptedNote, answeredNote, featureLevelQuestions, groupQuestions, questionsAbout } from "./questions.js";
import { failingCheckSummary } from "./ticket.js";
import { DRAFT_WATERMARK, gherkinDescription, indent, oneLine, parseGwt, titleOf } from "./text.js";

const SCENARIO_TITLE_MAX = 80;

function definitionComments(definitions: readonly Definition[]): string[] {
  return definitions.map((d) => `# Definition: ${oneLine(d.term)} — ${oneLine(d.definition)}`);
}

/** Accepted-outstanding first (the DoD wording), then answered, then unresolved (which only a draft can carry). */
function questionComments(questions: readonly QuestionCard[]): string[] {
  const groups = groupQuestions(questions);
  return [
    ...groups.accepted.map((q) => `# Open question (${acceptedNote(q)}): ${oneLine(q.text)}`),
    ...groups.answered.map((q) => `# Question (answered): ${oneLine(q.text)} — ${answeredNote(q)}`),
    ...groups.unresolved.map((q) => `# Question (unresolved): ${oneLine(q.text)}`),
  ];
}

/**
 * "Scenario: <title>", the example's questions as comments, then G/W/T steps or one "* <text>" step; each line unindented.
 * The title is the first sentence of the whitespace-collapsed text (≤ 80 chars at a word boundary), so a multi-line example
 * titles from its whole first sentence rather than its first line.
 */
function scenarioLines(example: ExampleCard, questions: readonly QuestionCard[]): string[] {
  const title = titleOf(oneLine(example.text), SCENARIO_TITLE_MAX) || example.id;
  const lines = [`Scenario: ${title}`];
  const body: string[] = questionComments(questionsAbout(questions, example.id));
  const gwt = parseGwt(example.text);
  if (gwt) {
    body.push(`Given ${gwt.given}`);
    if (gwt.when !== null) body.push(`When ${gwt.when}`);
    body.push(`Then ${gwt.then}`);
  } else {
    body.push(`* ${oneLine(example.text)}`);
  }
  lines.push(indent(body.join("\n"), 2));
  return lines;
}

export function feature(ctx: ExportContext): string {
  const out: string[] = [];
  if (ctx.draft) out.push(`# ${DRAFT_WATERMARK} — failing checks: ${failingCheckSummary(ctx)}`);
  const signoff = ctx.verified ? ctx.signoff : null;
  const verification = signoff ? `human verified by ${signoff.reviewer.name} at ${signoff.at}` : "NOT VERIFIED";
  out.push(`# Generated by Example Map Live from session ${ctx.session.id}, revision ${ctx.revision.hash}; ${verification}`);
  out.push(`@exmap @exmap-revision-${ctx.revision.hash.slice(0, 8)}${ctx.draft ? " @exmap-draft" : ""}`);
  out.push(`Feature: ${oneLine(ctx.title)}`);
  out.push(ctx.story ? indent(gherkinDescription(ctx.story.text), 2) : "  # No story card is recorded in this session");

  const featureComments = [
    ...definitionComments(ctx.story ? ctx.story.definitions : []),
    ...questionComments(featureLevelQuestions(ctx.questions, ctx.story, ctx.rules, ctx.examples)),
  ];
  if (featureComments.length > 0) out.push("", indent(featureComments.join("\n"), 2));

  for (const rule of ctx.rules) {
    out.push("");
    const [first = "", ...more] = rule.text.split("\n");
    out.push(`  Rule: ${first}`);
    if (more.length > 0) out.push(indent(gherkinDescription(more.join("\n")), 4));
    const ruleComments = [...definitionComments(rule.definitions), ...questionComments(questionsAbout(ctx.questions, rule.id))];
    if (ruleComments.length > 0) out.push(indent(ruleComments.join("\n"), 4));
    for (const example of ctx.examplesByRule.get(rule.id) ?? []) {
      out.push("");
      out.push(indent(scenarioLines(example, ctx.questions).join("\n"), 4));
    }
  }

  if (ctx.unattachedExamples.length > 0) {
    out.push("", "  # Examples not attached to a rule");
    ctx.unattachedExamples.forEach((example, i) => {
      if (i > 0) out.push("");
      out.push(indent(scenarioLines(example, ctx.questions).join("\n"), 2));
    });
  }

  return out.join("\n").replace(/\t/g, "  ").replace(/\n+$/, "") + "\n";
}
