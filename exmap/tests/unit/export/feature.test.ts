// TEST-PLAN §5.4 — feature.test.ts: requirement.feature (design §12.4), Gherkin from the live map.
import { describe, expect, it } from "vitest";
import { buildExportContext, exportFile, feature } from "../../../src/export/index.js";
import type { ExportContext } from "../../../src/export/index.js";
import {
  ACCEPT_REASON, ACCEPT_REASON_2, ANSWER_MESSAGE, EX_FREE, EX_UNATTACHED_FREE, OPTIONS, Q_AUDIT, Q_DENTIST, Q_MESSAGE, Q_RETRY, Q_TWICE,
  RULE_24H, RULE_OVERRIDE, SESSION, buildState, draftState, example, input, question, rule, story, verifiedState,
} from "./fixtures.js";

function ctxOf(state = verifiedState({ options: [OPTIONS] }), draft = false): ExportContext {
  const result = buildExportContext(input(state, draft));
  if (!result.ok) throw new Error(`fixture not exportable: ${result.signoff.status}`);
  return result.ctx;
}

const lines = (text: string): string[] => text.split("\n");
const indexOf = (text: string, needle: string): number => lines(text).findIndex((l) => l.includes(needle));
/** Index of the line that is exactly `line` (indentation included); -1 when absent. */
const lineAt = (text: string, line: string): number => lines(text).indexOf(line);

describe("requirement.feature", () => {
  it("opens with the generated-by comment, the tags and Feature: <title>, then the story indented two spaces", () => {
    const ctx = ctxOf();
    const out = feature(ctx);
    const head = lines(out).slice(0, 4);
    expect(head[0]).toBe(`# Generated by Example Map Live from session ${SESSION.id}, revision ${ctx.revision.hash}; human verified by Sam at 2026-10-16T12:20:00.000Z`);
    expect(head[1]).toBe(`@exmap @exmap-revision-${ctx.revision.hash.slice(0, 8)}`);
    expect(head[2]).toBe("Feature: A patient can cancel an appointment online, but not within two hours");
    expect(head[3]).toBe("  A patient can cancel an appointment online, but not within two hours.");
    expect(out).not.toContain("@exmap-draft");
    expect(out).not.toContain("DRAFT");
  });

  it("one Rule: per live rule in card_order, scenarios under their rule, each with G/W/T steps or a single * step", () => {
    const out = feature(ctxOf());
    const ruleLines = lines(out).filter((l) => l.startsWith("  Rule: "));
    expect(ruleLines).toEqual([`  Rule: ${RULE_24H}`, `  Rule: ${RULE_OVERRIDE}`]);
    const rule1 = indexOf(out, `Rule: ${RULE_24H}`);
    const rule2 = indexOf(out, `Rule: ${RULE_OVERRIDE}`);
    expect(rule1).toBeLessThan(rule2);
    const scenarioLines = lines(out).filter((l) => l.trim().startsWith("Scenario: "));
    expect(scenarioLines).toEqual([
      "    Scenario: Given a nurse appointment at 10am, when the patient cancels at 9am, then it is", // 80-char word-boundary cut
      "    Scenario: If a GP appointment is at 10am and they cancel at 7am then it is allowed",
      "    Scenario: For a nurse, if the appointment is at 10am and they cancel at 9am, then it is",
      "    Scenario: Given a receptionist opens a booking inside the window, when they try to cancel", // collapsed, not the first line
    ]);
    for (const s of scenarioLines) expect(s.length - 4).toBeLessThanOrEqual("Scenario: ".length + 80);
    expect(out).toContain("      Given a nurse appointment at 10am\n      When the patient cancels at 9am\n      Then it is refused\n");
    expect(out).toContain("      Given a GP appointment is at 10am and they cancel at 7am\n      Then it is allowed\n");
    expect(out).toContain(`      * ${EX_FREE}\n`);
    // the multi-line example parses once whitespace is collapsed
    expect(out).toContain("      Given a receptionist opens a booking inside the window\n      When they try to cancel it\n      Then the system refuses and shows the rule\n");
    // the fourth scenario sits under the second rule
    expect(indexOf(out, "Scenario: Given a receptionist")).toBeGreaterThan(rule2);
    expect(indexOf(out, `* ${EX_FREE}`)).toBeLessThan(rule2);
    expect(out).not.toContain("Background");
    expect(out).not.toContain("|");
  });

  it("questions are comments: accepted outstanding under their rule, answered inside the example's scenario, story-level after the story", () => {
    const out = feature(ctxOf());
    const accepted = `    # Open question (accepted as outstanding by Sam: ${ACCEPT_REASON} (no answer recorded)): ${Q_DENTIST}`;
    expect(out).toContain(accepted);
    expect(indexOf(out, Q_DENTIST)).toBeGreaterThan(indexOf(out, `Rule: ${RULE_24H}`));
    expect(indexOf(out, Q_DENTIST)).toBeLessThan(indexOf(out, "Scenario: Given a nurse appointment"));
    expect(out).toContain("accepted as outstanding");
    expect(out).toContain("practice manager");
    const answered = `      # Question (answered): ${Q_MESSAGE} — ${ANSWER_MESSAGE}`;
    expect(out).toContain(answered);
    expect(indexOf(out, Q_MESSAGE)).toBeGreaterThan(indexOf(out, "Scenario: Given a nurse appointment"));
    expect(lineAt(out, "      Given a nurse appointment at 10am")).toBeGreaterThan(-1);
    expect(indexOf(out, Q_MESSAGE)).toBeLessThan(lineAt(out, "      Given a nurse appointment at 10am"));
    expect(out).toContain(`  # Open question (accepted as outstanding by Sam: ${ACCEPT_REASON_2} (no answer recorded)): ${Q_TWICE}`);
    expect(indexOf(out, Q_TWICE)).toBeLessThan(indexOf(out, `Rule: ${RULE_24H}`));
    expect(out).not.toContain("Question (unresolved)");
  });

  it("definitions are comments: the story's after the story, a rule's inside its block", () => {
    const out = feature(ctxOf());
    expect(out).toContain("  # Definition: appointment — a booked slot, not a walk-in");
    expect(indexOf(out, "# Definition: appointment")).toBeLessThan(indexOf(out, `Rule: ${RULE_24H}`));
    const window = "    # Definition: cancellation window — the period before the appointment in which online cancellation is refused";
    expect(out).toContain(window);
    expect(indexOf(out, "# Definition: cancellation window")).toBeGreaterThan(indexOf(out, `Rule: ${RULE_OVERRIDE}`));
  });

  it("a draft carries the watermark comment, @exmap-draft, NOT VERIFIED, unattached examples and unresolved questions", () => {
    const out = feature(ctxOf(draftState(), true));
    const head = lines(out).slice(0, 4);
    expect(head[0]).toBe("# DRAFT / NOT VERIFIED — failing checks: story_rules_confirmed, examples_reviewed, changes_resolved, questions_resolved");
    expect(head[1]).toContain("; NOT VERIFIED");
    expect(head[2]).toMatch(/^@exmap @exmap-revision-[0-9a-f]{8} @exmap-draft$/);
    expect(head[3]).toBe("Feature: [DRAFT / NOT VERIFIED] A patient cancels an appointment online");
    expect(out).toContain("  # Examples not attached to a rule\n  Scenario: When the cancellation service is down, then the patient sees a retry message\n");
    expect(out).toContain("    Given the cancellation service is down\n    Then the patient sees a retry message\n");
    expect(out).toContain(`  Scenario: ${EX_UNATTACHED_FREE.replace(/\.$/, "")}\n    * ${EX_UNATTACHED_FREE}\n`);
    expect(indexOf(out, "# Examples not attached")).toBeGreaterThan(indexOf(out, "Scenario: Given a nurse appointment"));
    expect(out).toContain(`    # Question (unresolved): ${Q_AUDIT}`);
    expect(indexOf(out, Q_AUDIT)).toBeGreaterThan(indexOf(out, `Rule: ${RULE_24H}`));
    // the accepted question about the unattached example is a comment inside that scenario
    expect(out).toContain(`    # Open question (accepted as outstanding by Priya: UX to decide (no answer recorded)): ${Q_RETRY}`);
    expect(indexOf(out, Q_RETRY)).toBeGreaterThan(indexOf(out, "Scenario: When the cancellation service"));
    expect(indexOf(out, Q_RETRY)).toBeLessThan(indexOf(out, "Given the cancellation service is down"));
  });

  it("a rule with no examples still gets its block; multi-line rule text is indented line by line", () => {
    const state = buildState([
      story("card_1", 1, "Story line one\nstory line two"),
      rule("card_2", 2, "Rule first line\nrule second line\n\nrule fourth line"),
      rule("card_3", 3, "Rule with an example"),
      example("card_4", 4, "Given a\nmulti-line\nexample, then it\nis one step", "card_3"),
    ]);
    const out = feature(ctxOf(state, true));
    expect(out).toContain("Feature: [DRAFT / NOT VERIFIED] Story line one\n  Story line one\n  story line two\n");
    expect(out).toContain("  Rule: Rule first line\n    rule second line\n\n    rule fourth line\n");
    expect(out).toContain("  Rule: Rule with an example\n\n    Scenario: Given a multi-line example, then it is one step\n      Given a multi-line example\n      Then it is one step\n");
    expect(lines(out).filter((l) => /^\s+$/.test(l))).toEqual([]); // no whitespace-only lines
  });

  it("a question about a card that is not a live rule or example is a feature-level comment", () => {
    const state = buildState([
      story("card_1", 1, "A story"),
      question("card_8", 8, "About the story?", "card_1", { accepted: { by: "Sam", reason: "Later" } }),
      question("card_9", 9, "About another question?", "card_8", { accepted: { by: "Sam", reason: "Later still" } }),
      question("card_10", 10, "About nothing?", null, { answer: "Nothing." }),
    ]);
    const out = feature(ctxOf(state, true));
    expect(out).toContain(
      "  A story\n\n  # Open question (accepted as outstanding by Sam: Later (no answer recorded)): About the story?\n" +
        "  # Open question (accepted as outstanding by Sam: Later still (no answer recorded)): About another question?\n" +
        "  # Question (answered): About nothing? — Nothing.\n",
    );
  });

  it("has no tabs, ends with exactly one newline, and the file body is text/plain", () => {
    const state = buildState([story("card_1", 1, "A\tstory with a tab"), rule("card_2", 2, "Rule\twith\ttabs")]);
    const out = feature(ctxOf(state, true));
    expect(out).not.toContain("\t");
    expect(out.endsWith("\n")).toBe(true);
    expect(out.endsWith("\n\n")).toBe(false);
    const file = exportFile(input(verifiedState({ options: [OPTIONS] })), "requirement.feature");
    if (!file.ok) throw new Error("unreachable");
    expect(file.content_type).toBe("text/plain; charset=utf-8");
    expect(file.body).toBe(feature(ctxOf()));
    expect(file.body).toContain("Rule:");
    expect(file.body).toContain("Scenario:");
    expect(file.body).toContain("accepted as outstanding by Sam: To be settled with the practice manager");
  });
});

describe("requirement.feature: multi-line story and rule text cannot add Gherkin structure (review finding)", () => {
  it("a continuation line that starts with a Gherkin keyword is written as a comment, so no scenario or step is invented", () => {
    const s = story("card_story", 1, "A patient can cancel online\nScenario: injected scenario\n  Given the attacker typed this\n  Then cucumber runs it\n@tag\n| a | b |\n\"\"\"\nplain second line");
    const r = rule("card_rule", 2, "Not within two hours\nScenario: second injected\n  Given from a rule\nExamples:\nalso plain");
    const e = example("card_ex", 3, "Given a booking at 10am when the patient cancels at 9am then it is refused", "card_rule");
    const out = feature(ctxOf(buildState([s, r, e]), true));
    const structural = lines(out).filter((l) => /^\s*(Scenario|Examples|Rule|Feature|Background)\s*:|^\s*(Given|When|Then|And|But) |^\s*[@|]|^\s*"""/.test(l) && !/^\s*#/.test(l));
    expect(structural.filter((l) => /Scenario:/.test(l))).toHaveLength(1);
    expect(structural.filter((l) => /^\s*Given /.test(l))).toEqual(["      Given a booking at 10am"]);
    expect(structural.some((l) => /injected|attacker|from a rule|@tag|\| a \|/.test(l))).toBe(false);
    expect(out).toContain("  # Scenario: injected scenario");
    expect(out).toContain("  # Given the attacker typed this");
    expect(out).toContain("  plain second line");
    expect(out).toContain("  Rule: Not within two hours");
    expect(out).toContain("    # Scenario: second injected");
    expect(out).toContain("    also plain");
  });

  it("a first rule line that starts with a keyword is kept on the Rule: line, and a story whose first line does is commented", () => {
    const s = story("card_story", 1, "Scenario: story as a scenario");
    const r = rule("card_rule", 2, "Given a rule written as a step");
    const out = feature(ctxOf(buildState([s, r]), true));
    expect(out).toContain("  # Scenario: story as a scenario");
    expect(out).toContain("  Rule: Given a rule written as a step");
  });
});
